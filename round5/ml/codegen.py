FEATURES: List[str] = list(MODEL.get("features") or [MODEL.get("signal")])
FEATURE_MEANS: List[float] = list(MODEL.get("feature_means", []))
FEATURE_STDS: List[float] = list(MODEL.get("feature_stds", []))
COEFS: List[float] = list(MODEL.get("coefs", []))
INTERCEPT: float = float(MODEL.get("intercept", 0.0))


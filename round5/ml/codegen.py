def _ob_imbalances(od: OrderDepth) -> Tuple[float, float]:
    """obi_l1 (top-of-book) and obi_l3 (3-level) imbalance."""
    bids = od.buy_orders
    asks = od.sell_orders
    if not bids or not asks:
        return 0.0, 0.0
    bid_levels = sorted(bids.items(), key=lambda kv: -kv[0])[:3]
    ask_levels = sorted(asks.items(), key=lambda kv: kv[0])[:3]
    b1 = float(bid_levels[0][1]) if bid_levels else 0.0
    a1 = float(-ask_levels[0][1]) if ask_levels else 0.0
    bT = sum(float(v) for _, v in bid_levels)
    aT = sum(float(-v) for _, v in ask_levels)
    obi_l1 = (b1 - a1) / (b1 + a1) if (b1 + a1) > 0 else 0.0
    obi_l3 = (bT - aT) / (bT + aT) if (bT + aT) > 0 else 0.0
    return obi_l1, obi_l3


def _microprice_dev(od: OrderDepth, mid: float) -> float:
    bids = od.buy_orders
    asks = od.sell_orders
    if not bids or not asks:
        return 0.0
    best_bid = max(bids.keys())
    best_ask = min(asks.keys())
    b1 = float(bids[best_bid])
    a1 = float(-asks[best_ask])
    if (b1 + a1) <= 0:
        return 0.0
    micro = (best_bid * a1 + best_ask * b1) / (b1 + a1)
    return micro - mid


def _running_std(seq: List[float]) -> float:
    n = len(seq)
    if n < 2:
        return 0.0
    mu = sum(seq) / n
    var = sum((x - mu) ** 2 for x in seq) / (n - 1)
    return var ** 0.5


def compute_features(
    sym: str,
    od: OrderDepth,
    bid: int,
    ask: int,
    mid: float,
    mids_hist: Dict[str, List[float]],
    mpdev_hist: Dict[str, List[float]],
    ret1_hist: Dict[str, List[float]],
    flow_hist: Dict[str, List[float]],
    market_trades_now: List,
    fam_mpdev_lag5_now: float,
) -> Dict[str, float]:
    """Compute the 10-feature whitelist (or a subset matching MODEL features)."""
    feats: Dict[str, float] = {{}}
    obi_l1, obi_l3 = _ob_imbalances(od)
    mp_dev = _microprice_dev(od, mid)
    spread = float(ask - bid)
    spread_bps = (1e4 * spread / mid) if mid > 0 else 0.0

    mids = mids_hist.get(sym, [])
    if len(mids) >= 11:
        ret_10 = mid - mids[-11]
    else:
        ret_10 = 0.0

    r1 = ret1_hist.get(sym, [])
    ret_1_lag1 = r1[-2] if len(r1) >= 2 else 0.0

    if len(mids) >= 50:
        std_50 = _running_std(mids[-50:])
    else:
        std_50 = 0.0
    if len(mids) >= 50:
        std_500 = _running_std(mids[-500:]) if len(mids) >= 50 else 0.0
    else:
        std_500 = 0.0

    mpd_seq = mpdev_hist.get(sym, [])
    mp_dev_lag5 = mpd_seq[-6] if len(mpd_seq) >= 6 else 0.0

    flow = flow_hist.get(sym, [])
    if len(flow) >= 1:
        signed_flow_20 = float(sum(flow[-20:]))
    else:
        signed_flow_20 = 0.0
    # Update flow buffer with this tick's signed flow.
    new_flow_pts: float = 0.0
    for t in market_trades_now:
        try:
            price = float(t.price)
            qty = float(t.quantity)
        except Exception:
            continue
        sgn = 1.0 if price > mid else (-1.0 if price < mid else 0.0)
        new_flow_pts += sgn * qty
    flow.append(new_flow_pts)
    if len(flow) > TRADEFLOW_BUFFER_LEN:
        flow = flow[-TRADEFLOW_BUFFER_LEN:]
    flow_hist[sym] = flow

    feats["obi_l1"] = obi_l1
    feats["obi_l3"] = obi_l3
    feats["microprice_dev"] = mp_dev
    feats["spread_bps"] = spread_bps
    feats["ret_10"] = ret_10
    feats["ret_1_lag1"] = ret_1_lag1
    feats["signed_flow_20"] = signed_flow_20
    feats["std_500"] = std_500
    feats["std_50"] = std_50
    feats["microprice_dev_lag5"] = mp_dev_lag5
    feats["fam_mean_microprice_dev_lag5"] = fam_mpdev_lag5_now

    # Signal aliases for simple-signal kind:
    feats["momentum_10"] = ret_10
    feats["neg_spread"] = -spread

    # Live z-score of mid (50): only computable once mids has 50 entries.
    if len(mids) >= 50:
        recent = mids[-50:]
        mu = sum(recent) / 50
        sd = _running_std(recent)
        if sd > 0:
            feats["neg_zscore_mid_50"] = -(mid - mu) / sd
            feats["neg_zscore_vwap_50"] = feats["neg_zscore_mid_50"]  # vwap not tracked live
        else:
            feats["neg_zscore_mid_50"] = 0.0
            feats["neg_zscore_vwap_50"] = 0.0
    else:
        feats["neg_zscore_mid_50"] = 0.0
        feats["neg_zscore_vwap_50"] = 0.0

    feats["trade_imbalance"] = signed_flow_20  # alias used by simple-signal naming
    return feats


def predict_edge(features: Dict[str, float]) -> float:
    """Standardise + dot product."""
    edge = INTERCEPT
    for i, f in enumerate(FEATURES):
        x = float(features.get(f, 0.0))
        mu = FEATURE_MEANS[i] if i < len(FEATURE_MEANS) else 0.0
        sd = FEATURE_STDS[i] if i < len(FEATURE_STDS) else 1.0
        if sd == 0:
            sd = 1.0
        edge += COEFS[i] * (x - mu) / sd
    return edge



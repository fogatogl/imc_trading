POSITION_LIMIT = 10
BASE_QTY = 3                    # aggressive crossing size when |edge| > threshold
MID_BUFFER_LEN = 520            # std_500 needs 500 + small headroom
MPDEV_BUFFER_LEN = 8            # microprice_dev_lag5 + headroom
RET1_BUFFER_LEN = 4             # ret_1_lag1 needs 2-3
TRADEFLOW_BUFFER_LEN = 25       # signed_flow_20 + headroom
WARMUP_TICKS = 60               # need at least this many mids for ret_10/std_50

FAMILY = MODEL["family"]
KIND = MODEL["kind"]

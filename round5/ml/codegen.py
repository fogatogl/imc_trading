"""Codegen — JSON model artifact -> deployable Trader file.

Reads ``round5/ml/artifacts/<FAMILY>_{ridge,signal}.json`` and emits
``round5/strats/strat_ml_<FAMILY>.py`` that:
  - Embeds the artifact inline as a Python dict literal (Lambda forbids
    arbitrary file IO at runtime).
  - Maintains per-product mid/microprice_dev/trade-flow ring buffers in
    ``traderData`` so features can be computed tick-by-tick.
  - On each tick: computes the whitelist features, normalises with the
    artifact's stored mean/std, dot-products with coefs to get the
    predicted edge, applies ``live_haircut``, and crosses the spread when
    ``|edge| > 0.5 * spread + buffer``.

Both ``kind: ml_ridge`` and ``kind: simple_signal`` artifacts produce the
same trader shape — the simple-signal case is just a 1-feature model on a
single product. Codegen picks the right template branch from ``MODEL["kind"]``.

Usage::

    .venv/Scripts/python.exe round5/ml/codegen.py \\
        --artifact round5/ml/artifacts/PEBBLES_signal.json
    .venv/Scripts/python.exe round5/ml/codegen.py --all
"""

def _ob_imbalances(od: OrderDepth) -> Tuple[float, float]:
    bids = od.buy_orders
    asks = od.sell_orders
    if not bids or not asks:
        return 0.0, 0.0
    bid_levels = sorted(bids.items(), key=lambda kv: -kv[0])[:3]
    ask_levels = sorted(asks.items(), key=lambda kv: kv[0])[:3]
    b1 = float(bid_levels[0][1]) if bid_levels else 0.0
    a1 = float(-ask_levels[0][1]) if ask_levels else 0.0
    bT = sum(float(v) for _, v in bid_levels)
    aT = sum(float(-v) for _, v in ask_levels)
    obi_l1 = (b1 - a1) / (b1 + a1) if (b1 + a1) > 0 else 0.0
    obi_l3 = (bT - aT) / (bT + aT) if (bT + aT) > 0 else 0.0
    return obi_l1, obi_l3


def _microprice_dev(od: OrderDepth, mid: float) -> float:
    bids = od.buy_orders
    asks = od.sell_orders
    if not bids or not asks:
        return 0.0
    best_bid = max(bids.keys())
    best_ask = min(asks.keys())
    b1 = float(bids[best_bid])
    a1 = float(-asks[best_ask])
    if (b1 + a1) <= 0:
        return 0.0
    return (best_bid * a1 + best_ask * b1) / (b1 + a1) - mid


def _running_std(seq: List[float]) -> float:
    n = len(seq)
    if n < 2:
        return 0.0
    mu = sum(seq) / n
    var = sum((x - mu) ** 2 for x in seq) / (n - 1)
    return var ** 0.5


def compute_feature(name: str, sym: str, od: OrderDepth, bid: int, ask: int,
                    mid: float, mids: List[float], r1seq: List[float],
                    mpdev_seq: List[float], flow: List[float]) -> float:
    if name == "obi_l1":
        return _ob_imbalances(od)[0]
    if name == "obi_l3":
        return _ob_imbalances(od)[1]
    if name == "microprice_dev":
        return _microprice_dev(od, mid)
    if name == "spread_bps":
        return (1e4 * (ask - bid) / mid) if mid > 0 else 0.0
    if name == "neg_spread":
        return -float(ask - bid)
    if name == "ret_10" or name == "momentum_10":
        return (mid - mids[-11]) if len(mids) >= 11 else 0.0
    if name == "ret_1_lag1":
        return r1seq[-2] if len(r1seq) >= 2 else 0.0
    if name == "std_50":
        return _running_std(mids[-50:]) if len(mids) >= 10 else 0.0
    if name == "std_500":
        return _running_std(mids[-500:]) if len(mids) >= 50 else 0.0
    if name == "microprice_dev_lag5":
        return mpdev_seq[-6] if len(mpdev_seq) >= 6 else 0.0
    if name == "signed_flow_20" or name == "trade_imbalance":
        return float(sum(flow[-20:])) if flow else 0.0
    if name == "neg_zscore_mid_50" or name == "neg_zscore_vwap_50":
        if len(mids) < 50:
            return 0.0
        recent = mids[-50:]
        mu = sum(recent) / 50
        sd = _running_std(recent)
        return (-(mid - mu) / sd) if sd > 0 else 0.0
    return 0.0


def predict_edge(model: Dict[str, Any], sym: str, od: OrderDepth, bid: int,
                 ask: int, mid: float, mids: List[float], r1seq: List[float],
                 mpdev_seq: List[float], flow: List[float]) -> float:
    feats = list(model.get("features") or [model.get("signal")])
    mus = list(model.get("feature_means", [0.0] * len(feats)))
    sds = list(model.get("feature_stds", [1.0] * len(feats)))
    coefs = list(model.get("coefs", [0.0] * len(feats)))
    intercept = float(model.get("intercept", 0.0))
    edge = intercept
    for i, fname in enumerate(feats):
        x = compute_feature(fname, sym, od, bid, ask, mid, mids, r1seq, mpdev_seq, flow)
        mu = mus[i] if i < len(mus) else 0.0
        sd = sds[i] if i < len(sds) and sds[i] != 0 else 1.0
        edge += coefs[i] * (x - mu) / sd
    return edge



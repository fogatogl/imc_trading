"""Combine multiple model artifacts into one submission trader.

Reads N artifact JSONs (typically the surviving signal baselines) and emits a
single ``round5/strats/strat_ml_combined.py`` that:
  - Embeds all N models inline as a Python list of dicts.
  - Maintains per-product mid history + light microstructure buffers needed
    to compute every model's feature(s).
  - Each tick: for every model, compute its predicted edge on its target
    product(s) and place a crossing order if |edge| > 0.5*spread + buffer.

Models do NOT interact — each one drives independent positions on its own
product(s). The combined trader is exactly the disjoint union of the per-family
ones (per memory `feedback_pair_disjoint_legs`: no symbol owned by two models).
A pre-flight check enforces that.

Usage::

    .venv/Scripts/python.exe round5/ml/combine.py \\
        round5/ml/artifacts/MICROCHIP_signal.json \\
        round5/ml/artifacts/GALAXY_SOUNDS_signal.json \\
        round5/ml/artifacts/PANEL_signal.json \\
        round5/ml/artifacts/UV_VISOR_signal.json
"""

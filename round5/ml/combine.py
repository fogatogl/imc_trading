RET1_BUFFER_LEN = 4
TRADEFLOW_BUFFER_LEN = 25
WARMUP_TICKS = 60

# Build target -> model index lookup at module load.
TARGETS_BY_SYMBOL: Dict[str, int] = {{}}
for _i, _m in enumerate(MODELS):
    if _m["kind"] == "simple_signal":
        TARGETS_BY_SYMBOL[_m["product"]] = _i
    else:
        # ML kind would trade the whole family; not currently produced but supported.
        for _p in _m.get("family_products", []):
            TARGETS_BY_SYMBOL[_p] = _i

ALL_PRODUCTS: List[str] = sorted(TARGETS_BY_SYMBOL.keys())


